#!/usr/bin/env node
/* ============================================================================
   Builds `public/vendor/lucide-subset.js` from the icons this site actually
   references.

   Why
   ---
   The site used to ship `public/vendor/lucide.min.js` — 411 KB, byte-identical
   to the lucide@1.23.0 UMD bundle, i.e. all 1,990 icons. It uses a few hundred.
   On a mid-range Android that is a third of a megabyte to download, parse and
   execute before a single icon appears.

   Which icons
   -----------
   A plain `grep 'data-lucide="…"'` finds 183 names and would ship a broken
   site: a great many icons are chosen at runtime —
   `data-lucide="{{ $business->industry->icon ?? 'building-2' }}"`,
   `data-lucide="{{ $card['icon'] }}"` — from PHP arrays, config and database
   columns. A name that is not in the bundle renders nothing and only warns to
   the console, which is exactly the kind of breakage that ships unnoticed.

   So the harvest is deliberately generous: every single- or double-quoted
   kebab-case literal anywhere in resources/, app/, config/, routes/ and
   database/ that is *also* a real Lucide icon name is included. Over-inclusion
   costs about 250 bytes per icon; under-inclusion costs a missing icon on a
   page nobody screenshotted.

   API
   ---
   All 65 call sites call `lucide.createIcons()` with no arguments, so the
   subset defaults `icons` to itself. `replaceElement` below is a faithful copy
   of lucide 1.23.0's, including the `aria-hidden` rule, the `lucide
   lucide-<name>` class merge and attribute precedence, so the produced DOM is
   identical to what the full bundle produced.

   Run with `npm run build:icons`. Output is committed — the production host has
   no Node.
   ========================================================================== */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'public/vendor/lucide-subset.js');
const lucide = require(path.join(ROOT, 'node_modules/lucide/dist/cjs/lucide.js'));

/* lucide's own kebab → PascalCase, so `bar-chart-3` resolves to `BarChart3`. */
const toCamelCase = (s) => s.replace(/^([A-Z])|[\s-_]+(\w)/g, (m, p1, p2) => (p2 ? p2.toUpperCase() : p1.toLowerCase()));
const toPascalCase = (s) => { const c = toCamelCase(s); return c.charAt(0).toUpperCase() + c.slice(1); };

const SCAN_DIRS = ['resources', 'app', 'config', 'routes', 'database'];
const SCAN_EXT = /\.(blade\.php|php|json|js)$/;

function walk(dir, out = []) {
    if (!fs.existsSync(dir)) return out;
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
        if (['node_modules', 'vendor', '.git'].includes(e.name)) continue;
        const p = path.join(dir, e.name);
        if (e.isDirectory()) walk(p, out);
        else if (SCAN_EXT.test(e.name)) out.push(p);
    }
    return out;
}

const wanted = new Set();
const explicit = new Set();      // statically written data-lucide="…"
const missing = new Set();

for (const dir of SCAN_DIRS) {
    for (const file of walk(path.join(ROOT, dir))) {
        const src = fs.readFileSync(file, 'utf8');
        let m;

        const rStatic = /data-lucide="([a-z0-9][a-z0-9-]*)"/g;
        while ((m = rStatic.exec(src))) {
            explicit.add(m[1]);
            if (lucide.icons[toPascalCase(m[1])]) wanted.add(m[1]);
            else missing.add(m[1] + '  (' + path.relative(ROOT, file) + ')');
        }

        const rAny = /'([a-z0-9][a-z0-9-]*)'|"([a-z0-9][a-z0-9-]*)"/g;
        while ((m = rAny.exec(src))) {
            const name = m[1] || m[2];
            if (lucide.icons[toPascalCase(name)]) wanted.add(name);
        }
    }
}

const names = [...wanted].sort();
const icons = {};
for (const n of names) icons[toPascalCase(n)] = lucide.icons[toPascalCase(n)];

const banner = `/* lucide 1.23.0 (ISC) — ${names.length} of ${Object.keys(lucide.icons).length} icons.
   Generated by scripts/build-lucide-subset.cjs; do not edit by hand. */`;

const runtime = `${banner}
(function (g) {
  var icons = ${JSON.stringify(icons)};
  var defaults = {xmlns:"http://www.w3.org/2000/svg",width:24,height:24,viewBox:"0 0 24 24",fill:"none",stroke:"currentColor","stroke-width":2,"stroke-linecap":"round","stroke-linejoin":"round"};
  function svg(node) {
    var el = document.createElementNS("http://www.w3.org/2000/svg", node[0]);
    Object.keys(node[1]).forEach(function (k) { el.setAttribute(k, String(node[1][k])); });
    if (node[2] && node[2].length) node[2].forEach(function (c) { el.appendChild(svg(c)); });
    return el;
  }
  function createElement(iconNode, custom) {
    var attrs = Object.assign({}, defaults, custom || {});
    return svg(["svg", attrs, iconNode]);
  }
  function toCamel(s) { return s.replace(/^([A-Z])|[\\s-_]+(\\w)/g, function (m, p1, p2) { return p2 ? p2.toUpperCase() : p1.toLowerCase(); }); }
  function toPascal(s) { var c = toCamel(s); return c.charAt(0).toUpperCase() + c.slice(1); }
  function hasA11y(p) { for (var k in p) { if (k.indexOf("aria-") === 0 || k === "role" || k === "title") return true; } return false; }
  function mergeClasses() {
    var a = Array.prototype.slice.call(arguments);
    return a.filter(function (c, i) { return Boolean(c) && String(c).trim() !== "" && a.indexOf(c) === i; }).join(" ").trim();
  }
  function classNamesOf(attrs) {
    if (typeof attrs === "string") return attrs;
    if (!attrs || !attrs.class) return "";
    if (typeof attrs.class === "string") return attrs.class.split(" ");
    if (Array.isArray(attrs.class)) return attrs.class;
    return "";
  }
  function replaceElement(element, o) {
    var iconName = element.getAttribute(o.nameAttr);
    if (iconName == null) return;
    var iconNode = o.icons[toPascal(iconName)];
    if (!iconNode) return console.warn(element.outerHTML + " icon name was not found in the provided icons object.");
    var elementAttrs = Array.prototype.reduce.call(element.attributes, function (acc, a) { acc[a.name] = a.value; return acc; }, {});
    var aria = hasA11y(elementAttrs) ? {} : { "aria-hidden": "true" };
    var iconAttrs = Object.assign({}, defaults, { "data-lucide": iconName }, aria, o.attrs, elementAttrs);
    var cls = mergeClasses.apply(null, ["lucide", "lucide-" + iconName]
      .concat(classNamesOf(elementAttrs), classNamesOf(o.attrs)));
    if (cls) iconAttrs.class = cls;
    var el = createElement(iconNode, iconAttrs);
    return element.parentNode ? element.parentNode.replaceChild(el, element) : undefined;
  }
  function createIcons(opts) {
    opts = opts || {};
    var use = opts.icons && Object.keys(opts.icons).length ? opts.icons : icons;
    var nameAttr = opts.nameAttr || "data-lucide";
    var attrs = opts.attrs || {};
    var root = opts.root || document;
    Array.prototype.forEach.call(root.querySelectorAll("[" + nameAttr + "]"), function (el) {
      replaceElement(el, { nameAttr: nameAttr, icons: use, attrs: attrs });
    });
    if (opts.inTemplates) {
      Array.prototype.forEach.call(root.querySelectorAll("template"), function (tpl) {
        createIcons({ icons: use, nameAttr: nameAttr, attrs: attrs, root: tpl.content, inTemplates: true });
      });
    }
  }
  /* Any createIcons() call made before this file finished loading was captured
     by the stub in the page head (see pages/partials/icons.blade.php) and left
     on __lucideQueue. Take the queue before overwriting g.lucide, install the
     real API, then replay. The script tag is deferred, so it runs after the
     document is parsed and before DOMContentLoaded: the icons in the queued
     call are all present in the DOM by now. */
  var queued = g.__lucideQueue;
  g.lucide = { icons: icons, createIcons: createIcons, createElement: createElement, replaceElement: replaceElement };
  if (queued && queued.length) {
    for (var qi = 0; qi < queued.length; qi++) {
      try { createIcons(queued[qi] || {}); } catch (e) {}
    }
    g.__lucideQueue = null;
  }
})(typeof globalThis !== "undefined" ? globalThis : window);
`;

fs.writeFileSync(OUT, runtime);

const full = path.join(ROOT, 'node_modules/lucide/dist/umd/lucide.min.js');
console.log(`icons bundled : ${names.length} of ${Object.keys(lucide.icons).length}`);
console.log(`  of which written literally as data-lucide="…": ${explicit.size}`);
console.log(`output        : ${path.relative(ROOT, OUT)}  ${fs.statSync(OUT).size} bytes`);
if (fs.existsSync(full)) console.log(`full bundle   : ${fs.statSync(full).size} bytes`);
if (missing.size) {
    console.log('\ndata-lucide names that are NOT lucide icons (they render nothing today too):');
    for (const m of missing) console.log('  ' + m);
}
